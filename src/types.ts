import type { Address, Hex, WalletClient } from 'viem'
import type { ORDER_TYPES } from './orders.js'

export const PoolType = {
  AMM: 'AMM',
  FLASHLOAN: 'FLASHLOAN',
} as const

export type PoolType = (typeof PoolType)[keyof typeof PoolType]

interface BasePreparePoolParams {
  /** Address that owns and signs the pool orders. */
  maker: Address
  /** Fee charged by the maker (liquidity provider), in 1/100,000 units. For example, 1_000n is 1%. Valid range: 0n to 65_535n. */
  providerFee: bigint
  /** Address that receives the maker's provider fees. Defaults to the maker address. */
  providerFeeReceiver?: Address
  /** Future order expiration as a Unix timestamp in seconds, not milliseconds. */
  expiration: bigint
  /** Optional 72-bit pool nonce. A secure random value is generated by default. */
  poolNonce?: bigint
}

export interface PrepareAmmPoolParams extends BasePreparePoolParams {
  /** Selects an AMM pool. */
  type: typeof PoolType.AMM
  /** First input token. Tokens may be supplied in either address order. */
  tokenA: Address
  /** Second input token. Tokens may be supplied in either address order. */
  tokenB: Address
  /** Actual token A liquidity in its smallest unit, for example `parseUnits('1.5', 6)`. The SDK encodes it as `MAX_UINT256 - amountA`. */
  amountA: bigint
  /** Actual token B liquidity in its smallest unit. The SDK encodes it as `MAX_UINT256 - amountB`. */
  amountB: bigint
}

export interface PrepareFlashLoanPoolParams extends BasePreparePoolParams {
  /** Selects a flash-loan pool. */
  type: typeof PoolType.FLASHLOAN
  /** Token available for flash loans. */
  token: Address
  /** Actual available liquidity in the token's smallest unit, for example `parseUnits('1.5', 6)`. The SDK encodes it as `MAX_UINT256 - amount`. */
  amount: bigint
}

export type PreparePoolParams =
  PrepareAmmPoolParams | PrepareFlashLoanPoolParams

export interface PoolOrder {
  salt: bigint
  maker: Address
  receiver: Address
  makerAsset: Address
  takerAsset: Address
  makingAmount: bigint
  takingAmount: bigint
  makerTraits: bigint
  extension: Hex
}

export interface OrderTypedData {
  domain: {
    name: string
    version: string
    chainId: number
    verifyingContract: Address
  }
  types: typeof ORDER_TYPES
  primaryType: 'Order'
  message: PoolOrder
}

export interface PreparedPool {
  type: PoolType
  chainId: number
  orders: readonly PoolOrder[]
  typedData: readonly OrderTypedData[]
}

export interface SignedPool extends PreparedPool {
  signatures: readonly Hex[]
}

export interface CreatePoolResult {
  chainId: number
  poolId: Hex
  type: PoolType
}

export interface PoolAsset {
  /** Token contract address. Use this field to identify the asset. */
  token: Address
  /** Backend-cached token balance, or null when unavailable. */
  balance: bigint | null
  /** Backend-cached available balance, or null when unavailable. */
  availableBalance: bigint | null
}

export interface Pool {
  poolId: Hex
  chainId: number
  type: PoolType
  maker: Address
  /** Fee set by the maker providing liquidity, in 1/100,000 units. */
  providerFee: number
  /** Address that receives the liquidity provider fee. */
  providerFeeReceiver: Address
  expiresAt: string
  /** Pool assets have no positional tokenA/tokenB meaning. Match them by token address. */
  assets: PoolAsset[]
  orders: SignedOrder[]
}

export interface SignedOrder extends PoolOrder {
  signature: Hex
}

export const PoolStatus = {
  ACTIVE: 'ACTIVE',
  INACTIVE: 'INACTIVE',
} as const

export type PoolStatus = (typeof PoolStatus)[keyof typeof PoolStatus]

export interface PoolDetails extends Pool {
  status: PoolStatus
  expired: boolean
}

export interface PoolListResult {
  pools: Pool[]
  nextCursor: string | null
}

export interface BalanceFilters {
  /** Minimum balance for the first token in `tokens`. */
  A?: bigint
  /** Minimum balance for the second token in `tokens`. */
  B?: bigint
}

export interface GetPoolsParams {
  type: PoolType
  maker?: Address
  /** One or two token addresses. Filter labels A and B follow this array order. */
  tokens?: readonly [Address] | readonly [Address, Address]
  /** Minimum cached balances in token base units. Requires tokens. */
  minBalances?: BalanceFilters
  /** Minimum cached available balances in token base units. Requires tokens. */
  minAvailableBalances?: BalanceFilters
  cursor?: string
  limit?: number
}

export interface PoolTypeInfo {
  type: PoolType
  poolCount: number
}

export interface ChainInfo {
  chainId: number
  name: string
}

export interface Token {
  chainId: number
  address: Address
  symbol: string
  name: string
  decimals: number
  logo: string
}

export interface GetTokensParams {
  offset?: number
  limit?: number
}

export interface TokenListResult {
  tokens: Token[]
  total: number
  hasNextPage: boolean
  offset: number
  limit: number
}

export interface PoolBalances {
  /** Current balance of the supplied order's makerAsset. */
  makerAssetBalance: bigint
  /** Current balance of the supplied order's takerAsset. */
  takerAssetBalance: bigint
  /** Currently available balance of the supplied order's makerAsset. */
  availableMakerAssetBalance: bigint
  /** Currently available balance of the supplied order's takerAsset. */
  availableTakerAssetBalance: bigint
}

